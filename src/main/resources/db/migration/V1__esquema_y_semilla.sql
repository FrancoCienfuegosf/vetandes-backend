-- =====================================================================
-- V1: esquema y datos semilla de VetAndes (seccion 10 del examen)
--
-- propietario 1 ── N mascota 1 ── N atencion 1 ── N detalle_atencion N ── 1 prestacion
-- usuarios N ── M roles (tabla intermedia usuario_roles)
--
-- No se insertan ids a mano: las columnas IDENTITY los generan y las FK
-- se resuelven con subconsultas por dni, codigo o numero.
-- =====================================================================
CREATE TABLE propietario (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni VARCHAR2(8) NOT NULL UNIQUE, nombres VARCHAR2(120) NOT NULL,
  telefono VARCHAR2(15));
CREATE TABLE prestacion (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR2(7) NOT NULL UNIQUE, nombre VARCHAR2(80) NOT NULL,
  precio NUMBER(10,2) NOT NULL CHECK (precio > 0),
  especie_aplicable VARCHAR2(6) NOT NULL, activo NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE mascota (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(40) NOT NULL, especie VARCHAR2(6) NOT NULL,
  raza VARCHAR2(40), fecha_nacimiento DATE NOT NULL, sexo CHAR(1) NOT NULL,
  propietario_id NUMBER NOT NULL REFERENCES propietario(id),
  CONSTRAINT uq_mascota UNIQUE (nombre, propietario_id));
CREATE TABLE atencion (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(9) NOT NULL UNIQUE, fecha TIMESTAMP NOT NULL,
  mascota_id NUMBER NOT NULL REFERENCES mascota(id),
  peso NUMBER(5,2) NOT NULL, diagnostico VARCHAR2(300),
  estado VARCHAR2(12) NOT NULL, subtotal NUMBER(10,2) NOT NULL,
  descuento NUMBER(10,2) NOT NULL, total NUMBER(10,2) NOT NULL,
  usuario_registro VARCHAR2(30) NOT NULL, motivo_anulacion VARCHAR2(200));
CREATE TABLE detalle_atencion (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atencion_id NUMBER NOT NULL REFERENCES atencion(id),
  prestacion_id NUMBER NOT NULL REFERENCES prestacion(id),
  cantidad NUMBER(1) NOT NULL, precio_unitario NUMBER(10,2) NOT NULL,
  subtotal NUMBER(10,2) NOT NULL);

-- ---------------------------------------------------------------------
-- Seguridad (como en la sesion 10). password guarda el hash BCrypt.
-- Los permisos de cada rol NO estan en la base: estan en PermisosPorRol.
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(30) NOT NULL UNIQUE);
CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(30) NOT NULL UNIQUE,
  password VARCHAR2(100) NOT NULL,
  nombre_completo VARCHAR2(120) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE usuario_roles (
  usuario_id NUMBER NOT NULL REFERENCES usuarios(id),
  rol_id NUMBER NOT NULL REFERENCES roles(id),
  CONSTRAINT pk_usuario_roles PRIMARY KEY (usuario_id, rol_id));

